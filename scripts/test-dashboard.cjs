const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const { createRequire } = require('node:module');
const root = path.resolve(__dirname, '..');
const localRequire = createRequire(path.join(root, 'package.json'));
const ts = localRequire('typescript');
const React = localRequire('react');
const { renderToStaticMarkup } = localRequire('react-dom/server');
const cache = new Map();
function load(file) {
  if (!path.extname(file)) file = ['.tsx', '.ts', '.json'].map(ext => file + ext).find(fs.existsSync);
  assert.ok(file && fs.existsSync(file), 'The dashboard component should exist');
  if (file.endsWith('.json')) return JSON.parse(fs.readFileSync(file, 'utf8'));
  if (cache.has(file)) return cache.get(file);
  const module = { exports: {} }; cache.set(file, module.exports);
  const code = ts.transpileModule(fs.readFileSync(file, 'utf8'), { compilerOptions: { jsx: ts.JsxEmit.ReactJSX, module: ts.ModuleKind.CommonJS, esModuleInterop: true }}).outputText;
  vm.runInNewContext(code, {module, exports: module.exports, require: name => name.startsWith('.') ? load(path.resolve(path.dirname(file), name)) : localRequire(name), console, process: {env:{NEXT_PUBLIC_BASE_PATH:''}}, Intl, Date, setTimeout, clearTimeout, AbortController});
  cache.set(file, module.exports); return module.exports;
}
